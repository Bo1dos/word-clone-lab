/**
 * Область редактирования документа.
 * <p>
 * Этот класс представляет собой визуальный компонент, в котором отображается
 * и редактируется текст. Он управляет курсором, выделением и базовыми
 * операциями ввода (вставка, удаление). Хранит содержимое документа
 * в виде простой строки.
 * </p>
 *
 * @author Bo1dos
 * @version 1.0
 * @since 1.0
 */
public class DocumentArea {

    /**
     * Текущее содержимое документа. Пустая строка, если документ пуст.
     */
    private String text = "";
    
    /**
     * Вставляет текст в текущую позицию курсора.
     * <p>
     * Текст добавляется в конец существующего содержимого (упрощённая модель).
     * В реальном редакторе здесь была бы вставка в позицию курсора.
     * </p>
     *
     * @param s вставляемая строка (не может быть {@code null})
     * @throws NullPointerException если передан {@code null}
     */
    public void insertText(String s) {
        text += s;
        System.out.println("DocumentArea: inserted \"" + s + "\"");
    }
    
    /**
     * Удаляет выделенный фрагмент текста.
     * <p>
     * В текущей реализации только выводит сообщение в консоль.
     * В реальном редакторе здесь происходило бы удаление символов
     * с заданными индексами.
     * </p>
     *
     * @param start начальный индекс выделения (включительно)
     * @param end   конечный индекс выделения (исключительно)
     * @throws IndexOutOfBoundsException если индексы выходят за границы документа
     */
    public void deleteSelection(int start, int end) {
        System.out.println("DocumentArea: deleted selection");
    }
    
    /**
     * Возвращает весь текст документа.
     *
     * @return текущее содержимое документа (никогда не {@code null})
     */
    public String getText() {
        return text;
    }
}