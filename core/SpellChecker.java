/**
 * Проверка правописания, грамматики и тезаурус.
 * <p>
 * Модуль выполняет орфографическую проверку на основе встроенного словаря,
 * предлагает варианты исправления для слов с ошибками, а также может
 * предоставлять синонимы (тезаурус). В текущей версии поддерживается
 * только русский язык.
 * </p>
 *
 * @author Bo1dos
 * @version 1.0
 * @since 1.0
 */
public class SpellChecker {
    
    /**
     * Проверяет слово на наличие в словаре.
     * <p>
     * Если слово не найдено, в консоль выводится сообщение о возможной ошибке.
     * </p>
     *
     * @param word слово для проверки (не может быть {@code null})
     * @throws NullPointerException если передан {@code null}
     */
    public void checkWord(String word) {
        if (!word.matches("[а-яА-Я]+")) {  // простейшая проверка
            System.out.println("SpellChecker: possible misspelling: \"" + word + "\"");
        }
    }
    
    /**
     * Возвращает варианты исправления для ошибочного слова.
     * <p>
     * В текущей реализации возвращает фиксированный массив строк-заглушек.
     * В реальном приложении здесь был бы поиск по словарю.
     * </p>
     *
     * @param word слово с ошибкой
     * @return массив предложений (может быть пустым, если ничего не найдено)
     */
    public String[] suggestCorrections(String word) {
        System.out.println("SpellChecker: suggestions for \"" + word + "\"");
        return new String[]{"вариант1", "вариант2"};
    }
}