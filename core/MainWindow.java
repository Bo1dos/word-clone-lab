/**
 * Главное окно текстового редактора.
 * <p>
 * Отвечает за отображение ленточного интерфейса (Ribbon), панелей инструментов,
 * линеек и области документа. Управляет жизненным циклом приложения:
 * инициализация компонентов, отображение окна, обработка событий.
 * </p>
 *
 * @author Bo1dos
 * @version 1.0
 * @since 1.0
 */
public class MainWindow {
    
    /**
     * Инициализирует компоненты главного окна.
     * <p>
     * Создаёт ленту с вкладками, рабочую область документа и подключает
     * обработчики событий. Должен вызываться до {@link #show()}.
     * </p>
     */
    public void initialize() {
        System.out.println("MainWindow: Ribbon UI initialized");
    }
    
    /**
     * Отображает главное окно на экране.
     * <p>
     * Делает окно видимым. Перед вызовом этого метода окно должно быть
     * инициализировано вызовом {@link #initialize()}.
     * </p>
     *
     * @throws IllegalStateException если окно не было инициализировано
     */
    public void show() {
        System.out.println("MainWindow: displayed");
    }
}